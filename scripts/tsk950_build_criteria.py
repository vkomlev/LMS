def kumir_criteria(task_id: int) -> Dict[str, object]:
    sp = KUMIR_SPEC[task_id]
    must = [
        f"Закрашены {sp['target']} — и только они",
        sp["walk"],
        sp["gap"],
        KUMIR_COMMON_MUST,
        KUMIR_COMMON_MUST2,
    ]
    reject = [sp["err"]] + KUMIR_COMMON_REJECT
    notes = (
        "Ориентир (один из верных алгоритмов; проверен симулятором Робота на 200 случайных полях "
        "этого типа):\n" + reference_program(task_id).rstrip() + "\n" + TAIL_KUMIR
    )
    return {"must": must, "accept": list(KUMIR_COMMON_ACCEPT), "reject": reject, "notes": notes}


def main() -> None:
    out: Dict[str, Dict[str, object]] = {}
    for tid in sorted(SPECS):
        out[str(tid)] = python_criteria(tid)
    for tid in sorted(KUMIR_SPEC):
        assert tid in ROBOT_TASKS, tid
        out[str(tid)] = kumir_criteria(tid)
    # самопроверка ограничений схемы
    for tid, c in out.items():
        for fld in ("must", "accept", "reject"):
            items = c[fld]
            assert len(items) <= 20, (tid, fld)
            low = set()
            for it in items:
                it2 = " ".join(it.split())
                assert 10 <= len(it2) <= 500, (tid, fld, it2)
                assert it2.casefold() not in low, (tid, fld, it2)
                low.add(it2.casefold())
        assert len(c["notes"]) <= 2000, (tid, len(c["notes"]))
    OUT.write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"записано {len(out)} заданий → {OUT}")
    print("самая длинная notes:", max(len(c["notes"]) for c in out.values()))


if __name__ == "__main__":
    main()
