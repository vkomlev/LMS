def _fmt_case(stdin: str, out: str) -> str:
    return f"вход [{' '.join(stdin.split())}] → вывод [{' '.join(out.split())}]"


def python_criteria(task_id: int) -> Dict[str, object]:
    s = SPECS[task_id]
    rnd = random.Random(1000 + task_id)
    etalon = build_etalons(task_id)[0].rstrip()
    ref = _ref(task_id)
    cases = [_fmt_case(*s["sample"])]
    for _ in range(2):
        stdin, nums = _gen_input(task_id, rnd)
        cases.append(_fmt_case(stdin, ref(nums)))
    must: List[str] = []
    accept: List[str] = []
    reject: List[str] = []

    if s["fam"] == "A":
        kind, k = s["pred"]
        agg = s["agg"]
        cond = f"кратные {k} (x % {k} == 0)" if kind == "div" else f"оканчивающиеся на {k} (x % 10 == {k})"
        must.append("Программа сначала читает количество чисел N, затем ровно N чисел, по одному в строке")
        must.append(f"В обработку попадают только числа, {cond}; остальные не влияют на результат")
        must.append({
            "max": "Среди отобранных чисел ищется максимум; начальное значение не портит ответ (0 или первое подходящее число)",
            "min": "Среди отобранных чисел ищется минимум; начальное значение заведомо больше любого ввода (например 30001) или берётся первое подходящее число",
            "sum": "Складываются только отобранные числа, сумма накапливается за один проход",
            "count": "Считается количество отобранных чисел — счётчик увеличивается на 1, а не на само число",
        }[agg])
        must.append(f"Выводится одно число — результат; на примере из условия {cases[0]}")
        accept.append("Любые имена переменных; цикл for или while; накопление по ходу ввода или сначала список, потом обработка")
        if kind == "end":
            accept.append(f"Проверка последней цифры через str(x)[-1] == '{k}' наравне с x % 10 == {k}")
        accept.append("Использование встроенных max/min/sum/len по отфильтрованному списку")
        reject.append("Программа не читает N первым числом: читает до 0 или фиксированное количество раз")
        reject.append("Условие отбора перепутано: кратность вместо последней цифры или наоборот, другой делитель или другая цифра")
        reject.append({
            "max": "Начальное значение максимума взято из первого введённого числа без проверки условия — ответ может быть числом, не подходящим под условие",
            "min": "Начальный минимум равен 0 — ответ всегда 0; или первое число взято без проверки условия",
            "sum": "Выводится количество подходящих чисел или сами числа вместо суммы",
            "count": "Выводится сумма или сами подходящие числа вместо их количества",
        }[agg])
        reject.append("Результат печатается внутри цикла на каждом шаге, а не один раз после ввода")
    elif s["fam"] == "B":
        d = s["end"]
        must.append("Числа читаются до появления 0; сам 0 в обработку не попадает, после него ввод прекращается")
        must.append(f"Проверяются оба условия одновременно: число кратно 6 (x % 6 == 0) и оканчивается на {d} (x % 10 == {d})")
        must.append("Подходящие числа суммируются; после окончания ввода выводится одна сумма")
        must.append(f"На примере из условия {cases[0]}")
        accept.append("Любые имена переменных; цикл while x != 0 с чтением в конце тела или while True с break при 0")
        accept.append(f"Объединённая проверка x % 30 == {(d if d % 6 == 0 else next(v for v in range(30) if v % 6 == 0 and v % 10 == d))} вместо двух условий, если она равносильна")
        accept.append("Сначала список всех чисел, затем сумма по условию")
        reject.append("Проверяется только одно из двух условий (только кратность 6 или только последняя цифра)")
        reject.append("Программа читает количество чисел N первым числом — в этом задании его нет")
        reject.append("0 обрабатывается как обычное число или цикл не завершается при 0")
        reject.append("Условия соединены «или» вместо «и»")
    elif s["fam"] == "C":
        must.append("Числа читаются до появления 0; сам 0 в последовательность не входит")
        must.append("Находятся два наибольших и два наименьших числа; при повторяющихся значениях учитываются оба (например 25 и 25)")
        must.append("Выводятся две суммы в указанном порядке: сначала сумма двух наибольших, затем сумма двух наименьших, каждая на своей строке")
        must.append(f"На примере из условия {cases[0]}")
        accept.append("Сортировка списка и a[-1] + a[-2], a[0] + a[1] либо отслеживание четырёх переменных по ходу ввода")
        accept.append("Отрицательные числа обрабатываются как обычные целые")
        reject.append("Порядок сумм перепутан: сначала наименьшие")
        reject.append("Второй максимум ищется среди чисел строго меньше первого — повторяющиеся значения теряются")
        reject.append("Выводится сумма всех чисел или разность максимума и минимума")
    else:
        agg = s["agg"]
        op, lim = s["cond"]
        op_words = {"<": "меньше", ">": "больше", ">=": "не меньше"}[op]
        must.append("Программа читает N, затем N скоростей, по одной в строке")
        must.append({
            "max": "Ищется максимальная скорость среди всех введённых",
            "min": "Ищется минимальная скорость среди всех введённых (начальное значение заведомо больше 300 или первая скорость)",
            "avg": "Считается средняя скорость: сумма всех делённая на N",
        }[agg])
        must.append(f"YES выводится, если ХОТЯ БЫ ОДНА скорость {op_words} {lim} (v {op} {lim}); иначе NO — флаг ставится один раз и не сбрасывается")
        must.append(("Средняя выводится с одним знаком после запятой: round(s / n, 1) или f'{s / n:.1f}'; " if agg == "avg" else "")
                    + "Вывод в две строки: сначала число, затем YES или NO заглавными латинскими буквами")
        must.append(f"На примере из условия {cases[0]}")
        accept.append("Любые имена переменных; список с max/min/sum или накопление в цикле")
        accept.append("Флаг как логическая переменная, счётчик или сразу строка 'YES'/'NO'")
        accept.append("Тернарный вывод print('YES' if f else 'NO')")
        reject.append(f"Строгость неравенства перепутана ({'>=' if op == '>' else '>' if op == '>=' else '<='} вместо {op}) — на граничном значении {lim} ответ неверен")
        reject.append("Проверяется только последняя скорость, а не хотя бы одна из всех")
        reject.append("YES/NO выведены строчными буквами, кириллицей или с лишним текстом")
        reject.append("Порядок строк вывода перепутан или значения выведены в одну строку")
        if agg == "avg":
            reject.append("Средняя выведена без округления до одного знака (например 75.55 или 75)")

    notes = (
        "Эталон (один из многих верных; проверен исполнением на примере из условия и 6 случайных тестах):\n"
        f"{etalon}\n\nТесты: " + "; ".join(cases) + ".\n" + TAIL_PY
    )
    return {"must": must, "accept": accept, "reject": reject, "notes": notes}


