def _dsn() -> str:
    """Прод-DSN learn из .mcp.json (в код не хардкодим)."""
    env = os.environ.get("LEARN_PROD_DSN") or os.environ.get("DATABASE_URL", "")
    dsn = env.replace("postgresql+asyncpg://", "postgresql://")
    if "5.42.107.253" not in dsn:
        cfg = json.loads((project_root / ".mcp.json").read_text(encoding="utf-8"))
        for arg in cfg["mcpServers"]["learn_prod_db"]["args"]:
            if isinstance(arg, str) and arg.startswith("postgresql://"):
                dsn = arg.split("?")[0]
                break
    if "5.42.107.253" not in dsn or "/learn" not in dsn:
        raise RuntimeError("Не нашёл прод-DSN learn (5.42.107.253/learn).")
    return dsn


def _norm(text: str) -> str:
    """Неразрывный пробел -> обычный. Длина сохраняется, индексы остаются валидными."""
    return text.replace(" ", " ")


def transform(stem: str, edits: list[tuple[str, str]], task_id: int) -> str:
    """Применить замены, требуя ровно одного вхождения каждой (с учётом NBSP)."""
    out = stem
    for old, new in edits:
        norm, target = _norm(out), _norm(old)
        found = norm.count(target)
        if found != 1:
            raise AssertionError(
                f"id={task_id}: подстрока встречается {found} раз, ожидалась 1:\n  {old[:120]}"
            )
        i = norm.index(target)
        out = out[:i] + new + out[i + len(target):]
    return out


def _as_dict(raw: object) -> dict:
    """jsonb из asyncpg приходит строкой либо словарём — привести к словарю."""
    if isinstance(raw, str):
        return json.loads(raw)
    return dict(raw)  # type: ignore[arg-type]


async def main(apply: bool) -> None:
    """Переписать условия в одной транзакции; без --apply — откат."""
    conn = await asyncpg.connect(_dsn())
    report: list[str] = [
        "# tsk-820: было → станет",
        "",
        "Правка условий 11 заданий курсов 147 и 1397: оборот «неудачный ход» приведён к "
        "единственному прочтению A. Эталоны не тронуты (проверено внутри транзакции).",
        "",
    ]
    try:
        async with conn.transaction():
            ids = [tid for tid, _c, _l, _e in PLAN]
            rows = await conn.fetch(
                "SELECT id, task_content, solution_rules FROM tasks "
                "WHERE id = ANY($1::int[]) AND is_active = true FOR UPDATE",
                ids,
            )
            if len(rows) != len(ids):
                raise AssertionError(f"ожидал {len(ids)} активных задач, нашёл {len(rows)}")
            by_id = {r["id"]: r for r in rows}

            etalons_before = {
                tid: _as_dict(by_id[tid]["solution_rules"])["short_answer"]["accepted_answers"]
                for tid in ids
            }

            for tid, course, label, edits in PLAN:
                content = _as_dict(by_id[tid]["task_content"])
                old_stem = content.get("stem", "")
                new_stem = transform(old_stem, edits, tid)
                content["stem"] = new_stem

                report.append(f"## Задание {tid} (курс {course}) — {label}")
                report.append("")
                for old, new in edits:
                    report.append(f"- **было:** {old}")
                    report.append(f"- **станет:** {new}")
                    report.append("")
                print(
                    f"id={tid} курс={course}: замен {len(edits)}, "
                    f"длина stem {len(old_stem)} -> {len(new_stem)}"
                )

                await conn.execute(
                    "UPDATE tasks SET task_content = $1::jsonb WHERE id = $2",
                    json.dumps(content, ensure_ascii=False),
                    tid,
                )

            # Проверка ВНУТРИ транзакции: тексты изменились, эталоны — нет.
            verify = await conn.fetch(
                "SELECT id, task_content->>'stem' AS stem, solution_rules FROM tasks "
                "WHERE id = ANY($1::int[])",
                ids,
            )
            edits_by_id = {tid: e for tid, _c, _l, e in PLAN}
            for r in verify:
                stem = _norm(r["stem"] or "")
                now = _as_dict(r["solution_rules"])["short_answer"]["accepted_answers"]
                if now != etalons_before[r["id"]]:
                    raise AssertionError(f"id={r['id']}: эталон изменился — это запрещено")
                for old, new in edits_by_id[r["id"]]:
                    # Добавляющая замена (old целиком входит в new) старый текст сохраняет
                    # намеренно — например, определение вставлено ПЕРЕД прежней фразой.
                    if _norm(old) not in _norm(new) and _norm(old) in stem:
                        raise AssertionError(f"id={r['id']}: старый текст остался: {old[:80]}")
                    if _norm(new) not in stem:
                        raise AssertionError(f"id={r['id']}: новый текст не найден: {new[:80]}")
                if "хотя бы один неудачный" not in stem:
                    raise AssertionError(f"id={r['id']}: нет оборота «хотя бы один неудачный»")
                if "независимо от того, был ли у него выигрышный ход" not in stem:
                    raise AssertionError(f"id={r['id']}: нет определения неудачного хода")
            print(
                f"\nПроверка внутри транзакции: {len(verify)}/{len(ids)} обновлены, "
                "эталоны не тронуты. OK"
            )

            if not apply:
                raise RuntimeError("DRY-RUN: откатываю (запусти с --apply при DBCHECK_OK=1)")

        REPORT.parent.mkdir(parents=True, exist_ok=True)
        REPORT.write_text("\n".join(report), encoding="utf-8")
        print(f"\nЗАПИСАНО И ЗАКОММИЧЕНО. Дифф: {REPORT}")
    finally:
        await conn.close()


