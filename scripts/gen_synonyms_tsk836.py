def prod_dsn() -> Dict[str, Any]:
    """Параметры подключения к боевой базе из `.mcp.json` (пароль не печатаем)."""
    mcp = json.loads((PROJECT_ROOT / ".mcp.json").read_text(encoding="utf-8"))
    parsed = urlparse(mcp["mcpServers"]["learn_prod_db"]["args"][-1])
    return dict(
        host=parsed.hostname,
        port=parsed.port or 5432,
        dbname=(parsed.path or "").lstrip("/"),
        user=unquote(parsed.username or ""),
        password=unquote(parsed.password or ""),
    )


def main() -> int:
    dsn = prod_dsn()
    logger.info("Читаю боевую базу: %s@%s/%s", dsn["user"], dsn["host"], dsn["dbname"])
    conn = psycopg2.connect(**dsn)
    cur = conn.cursor(cursor_factory=psycopg2.extras.RealDictCursor)
    cur.execute(
        """
        SELECT id,
               course_id,
               task_content->>'stem'  AS stem,
               task_content->>'title' AS title,
               solution_rules->'short_answer'->'accepted_answers' AS accepted
        FROM tasks
        WHERE id = ANY(%s) AND is_active = true
        ORDER BY id
        """,
        (list(PLAN),),
    )
    rows = {r["id"]: r for r in cur.fetchall()}
    conn.close()

    items: List[Dict[str, Any]] = []
    report: List[str] = [
        "# tsk-836 — синонимы в заданиях со словом-эталоном (на вычитку)",
        "",
        f"Дата: {date.today().isoformat()}. Источник: боевая база `learn`, только "
        "активные задания. План строго на ДОБАВЛЕНИЕ: ни один существующий вариант "
        "не удаляется и не переписывается, балл добавленного равен баллу эталона.",
        "",
        "## Применяем",
        "",
    ]

    for task_id, spec in PLAN.items():
        row = rows.get(task_id)
        if row is None:
            logger.error("%s: задание не найдено или выключено — пропускаю", task_id)
            continue
        before = [{"value": a.get("value"), "score": a.get("score")} for a in row["accepted"]]
        existing = {(a["value"] or "").strip().lower() for a in before}
        add = [w for w in spec["add"] if w.strip().lower() not in existing]
        skipped = [w for w in spec["add"] if w.strip().lower() in existing]
        if not add:
            logger.info("%s: все синонимы уже приняты — пропускаю", task_id)
            continue
        items.append({"task_id": task_id, "before": before, "add": add})
        report += [
            f"### {task_id} (курс {row['course_id']}) — {row['title']}",
            "",
            f"**Условие.** {(row['stem'] or '').strip()}",
            "",
            f"**Принимается сейчас ({len(before)}).** " + ", ".join(
                f"`{a['value']}`" for a in before),
            "",
            f"**Добавляем ({len(add)}).** " + ", ".join(f"`{w}`" for w in add),
            "",
            f"**Почему.** {spec['why']}",
            "",
        ]
        if skipped:
            report += [f"*Уже было, не дублируем: {', '.join(skipped)}.*", ""]

    report += ["## Не применено — решать оператору", ""]
    for d in DECLINED:
        report += [f"- **{d['task']}** ← `{d['synonym']}`. {d['why']}", ""]

    report += [
        "## Задания про интерфейс платформы — отдельный список, в проход не входят",
        "",
        "Ученики называют разделы, которые в кабинете действительно есть: вопрос "
        "допускает несколько верных названий и лечится формулировкой, а не списком "
        "ответов.",
        "",
    ]
    for t in INTERFACE_TASKS:
        report += [f"- {t}", ""]

    PLAN_PATH.write_text(
        json.dumps({"generated": date.today().isoformat(), "apply": items},
                   ensure_ascii=False, indent=1),
        encoding="utf-8",
    )
    REPORT_PATH.write_text("\n".join(report), encoding="utf-8")
    logger.info("План: %s (%d заданий, %d вариантов)", PLAN_PATH,
                len(items), sum(len(i["add"]) for i in items))
    logger.info("Отчёт на вычитку: %s", REPORT_PATH)
    return 0


if __name__ == "__main__":
    sys.exit(main())
