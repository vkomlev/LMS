def prod_dsn() -> Dict[str, Any]:
    """Параметры подключения к боевой базе из `.mcp.json` (пароль не печатаем)."""
    mcp = json.loads((PROJECT_ROOT / ".mcp.json").read_text(encoding="utf-8"))
    parsed = urlparse(mcp["mcpServers"]["learn_prod_db"]["args"][-1])
    return dict(
        host=parsed.hostname,
        port=parsed.port or 5432,
        dbname=(parsed.path or "").lstrip("/"),
        user=unquote(parsed.username or ""),
        password=unquote(parsed.password or ""),
    )


def main() -> int:
    conn = psycopg2.connect(**prod_dsn())
    conn.set_session(readonly=True, autocommit=True)
    cur = conn.cursor(cursor_factory=psycopg2.extras.RealDictCursor)

    items: List[Dict[str, Any]] = []
    for task_id, etalon, forms, why in MANUAL:
        cur.execute(
            "SELECT solution_rules->'short_answer'->'accepted_answers' AS accepted, "
            "       task_content->>'stem' AS stem "
            "FROM tasks WHERE id = %s AND is_active = true",
            (task_id,),
        )
        row = cur.fetchone()
        if row is None:
            logger.warning("%s: задание не найдено или выключено — пропуск", task_id)
            continue
        accepted = row["accepted"] or []
        values = [a.get("value") for a in accepted]
        if not values or values[0] != etalon:
            # Первым элементом обязан стоять исходный эталон: на этом держится
            # разбор гостевой диагностики. Хвост мог вырасти первой партией —
            # это нормально, новые формы просто дедуплицируются об него.
            logger.warning("%s: первый эталон в базе %r, ожидался %r — пропуск",
                           task_id, values[:1], etalon)
            continue
        new = [f for f in forms if f.strip().lower() not in {v.strip().lower() for v in values}]
        items.append({
            "task_id": task_id,
            "etalon": etalon,
            "add": new,
            "before": accepted,
            "why": why,
            "stem": (row["stem"] or "").strip(),
        })
        logger.info("%s [%s] +%d: %s", task_id, etalon, len(new), ", ".join(new))

    conn.close()
    OUT_PATH.write_text(
        json.dumps(
            {"generated_at": date.today().isoformat(), "task": "tsk-796",
             "kind": "manual", "apply": items, "skipped": []},
            ensure_ascii=False, indent=1),
        encoding="utf-8",
    )
    logger.info("План: %s — заданий %d, форм %d",
                OUT_PATH, len(items), sum(len(i["add"]) for i in items))
    return 0


if __name__ == "__main__":
    sys.exit(main())
