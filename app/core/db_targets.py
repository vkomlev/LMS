# -*- coding: utf-8 -*-
"""Куда смотрит подключение: боевая база или нет (tsk-885).

ЕДИНСТВЕННОЕ место, где живёт список признаков боевой БД. Раньше он лежал в
`tests/run_database.py` — то есть был доступен только прогону тестов, а
разовым скриптам приходилось либо повторять его, либо не проверять вовсе.
Не проверяли. Скрипт `cleanup_test_artifacts.py` удалял всех пользователей,
кроме трёх названных, и никакой преграды между ним и боевой базой не было —
только надежда, что `.env` смотрит в dev. Сам он удалён (решение оператора
10.09), но такой же отбор «всё, кроме белого списка» напишется снова, и
преграда нужна не ему одному.
"""
from __future__ import annotations

import os
from typing import Optional

#: Признаки боевой БД LMS: хост и роль. Совпадения по подстроке достаточно —
#: DSN бывает записан и с портом, и с параметрами.
PROD_DB_SIGNATURES: tuple[str, ...] = ("5.42.107.253", "lms_prod")


def is_prod_dsn(dsn: Optional[str]) -> bool:
    """Указывает ли строка подключения на боевую базу."""
    low = (dsn or "").lower()
    return any(signature in low for signature in PROD_DB_SIGNATURES)


def assert_not_prod(dsn: Optional[str] = None, *, what: str = "эта операция") -> None:
    """Отказать, если подключение боевое.

    Зовётся разовыми скриптами, которые чистят следы тестов: их условия
    отбора («все пользователи, кроме трёх», «email на @example.») на боевых
    данных означают совсем не то, что задумано.

    Args:
        dsn: строка подключения; по умолчанию — `DATABASE_URL` из окружения.
        what: что именно отказываемся делать — попадёт в текст ошибки.

    Raises:
        RuntimeError: подключение боевое.
    """
    target = dsn if dsn is not None else os.getenv("DATABASE_URL")
    if is_prod_dsn(target):
        raise RuntimeError(
            f"СТОП: {what} не выполняется на боевой базе. "
            "Скрипт разбирает следы тестовых прогонов, и его условия отбора "
            "на боевых данных означают другое. Переключите DATABASE_URL на "
            "dev-базу."
        )
