_SOFT_LIMIT_NOTE = """\
ВАЖНО: разговор уже длинный. Если ученик всё ещё не сдвинулся, мягко предложи ему
позвать преподавателя — не как отказ, а как нормальный следующий шаг. Продолжай
помогать, но без новых заходов по кругу.
"""


@dataclass(frozen=True)
class TutorTaskView:
    """То, что наставник знает о задании. Эталона тут НЕТ ФИЗИЧЕСКИ.

    Отдельный тип, а не срез с `TaskRead`, ровно по этой причине: у `TaskRead`
    есть поле `solution_rules`, и любой рефакторинг, добавляющий «ну передадим
    задание целиком», мгновенно протащил бы эталон в промпт. Здесь передавать
    нечего — поля просто не существует.

    Утечка эталона молчалива: она не падает тестом, не пишется в лог и видна
    только по тому, что ученик внезапно знает ответ. Поэтому защита структурная.
    """

    task_id: int
    stem: str
    task_type: str
    is_single_construct: bool = False
    course_title: str | None = None

    @classmethod
    def from_task(cls, task, course_title: str | None = None) -> "TutorTaskView":
        """Собрать вид задания из ORM-объекта, взяв ТОЛЬКО безопасные поля."""
        content = task.task_content if isinstance(task.task_content, dict) else {}
        stem = str(content.get("stem") or content.get("question") or "").strip()
        return cls(
            task_id=int(task.id),
            stem=stem,
            task_type=str(content.get("type") or "SA"),
            is_single_construct=_looks_single_construct(content),
            course_title=course_title,
        )


def _looks_single_construct(content: dict) -> bool:
    """Одноконструкционное ли задание — по форме, а не по теме.

    Признак грубый и намеренно осторожный: лучше лишний раз включить строгий
    режим, чем выдать ответ на «тонкой» задаче. Выбор с запасом в сторону
    строгости — прямое следствие §8 методики, где этот класс назван самым хрупким.
    """
    ttype = str(content.get("type") or "").upper()
    if ttype in ("SC", "MC", "SC_QW", "MC_QW"):
        # Выбор варианта: любой разбор вариантов почти равен ответу.
        return True
    stem = str(content.get("stem") or content.get("question") or "")
    # Короткая формулировка без переносов — обычно микрозадача в один приём.
    return len(stem) < 220 and stem.count("\n") <= 1


# Признаки практической миссии — по КРИТЕРИЯМ ПРИЁМКИ, а не по теме. Задание,
# которое принимается по артефакту («приложи скрин», «впиши команду»), проверяет
# результат действия, а не рассуждение. Разбирать там ход мысли нечего.
_MISSION_MARKERS = (
    "приложи", "приложен", "артефакт", "скрин", "скриншот",
    "принято, если", "критерии приёмки", "миссия",
)


def looks_like_mission(stem: str) -> bool:
    """Практическая миссия ли это.

    Смотрим на формулировку приёмки, а не на тему: «настрой агента» и «настрой
    почту» — разные темы с одинаковым видом помощи.
    """
    low = (stem or "").lower()
    return sum(1 for m in _MISSION_MARKERS if m in low) >= 2


def pick_mode(view: TutorTaskView, has_student_code: bool) -> TutorMode:
    """Выбрать режим по заданию и тому, что принёс ученик.

    Порядок проверок не случаен.

    Миссия проверяется ПЕРВОЙ: если задание сдаётся артефактом, любой другой
    режим начнёт разбирать несуществующий алгоритм. Ровно это и произошло с
    первым реальным учеником — он закрыл окно после первого же вопроса.

    Дальше «тонкое» задание сильнее остального: даже если ученик прислал код,
    показывать конструкцию с числами нельзя.
    """
    if looks_like_mission(view.stem):
        return "mission"
    if view.is_single_construct:
        return "thin"
    if has_student_code:
        return "debug"
    return "concept"


def build_system_prompt(view: TutorTaskView, mode: TutorMode, *, soft_limit: bool = False) -> str:
    """Собрать системную инструкцию наставника.

    Задание попадает в промпт как ДАННЫЕ (в секции ученика), а не как часть
    инструкции: иначе формулировка задания, содержащая слова вроде «выведи
    ответ», читалась бы наставником как команда ему.
    """
    parts = [_CORE.format(open=STUDENT_DATA_OPEN, close=STUDENT_DATA_CLOSE), _MODES[mode]]
    if soft_limit:
        parts.append(_SOFT_LIMIT_NOTE)
    return "\n".join(parts).strip()


def build_context_block(view: TutorTaskView, student_answer: str | None) -> str:
    """Секция данных: условие задания и ответ, с которым ученик пришёл.

    Обе величины — чужой текст, поэтому обёрнуты метками и объявлены данными.
    Ответ ученика подставляется программно (он не набирал его в этом чате), и
    именно поэтому он опаснее обычной реплики: ученик может заранее вписать в
    поле ответа «инструкцию» наставнику и сдать заведомо неверно, чтобы её
    протащить. Девятый регресс-сценарий сверх восьми из методики проверяет ровно
    это.
    """
    lines = [STUDENT_DATA_OPEN, "Задание, над которым работает ученик:", view.stem.strip()]
    if student_answer and student_answer.strip():
        lines += ["", "Ответ, который ученик отправил и который не был принят:",
                  student_answer.strip()]
    lines.append(STUDENT_DATA_CLOSE)
    return "\n".join(lines)


def build_opening_user_message(view: TutorTaskView, student_answer: str | None) -> str:
    """Первая реплика в диалоге: данные + просьба начать с вопроса о ходе мысли.

    Решение оператора 11: наставник знает задание, но не объясняет сразу — он
    спрашивает, что ученик уже попробовал. Подсказка до попытки — то, ради отказа
    от чего методика и писалась.
    """
    if not (student_answer and student_answer.strip()):
        # Ученик пришёл ДО первой сдачи: спрашивать «что уже попробовал»
        # бессмысленно — ответить нечего, кроме «ничего», и на этом разговор
        # заканчивается. Именно так ушёл первый реальный ученик.
        opening = (
            "Начни разговор: поздоровайся одной строкой и спроси, что именно в "
            "задании непонятно или где он застрял. Ученик ещё НЕ отправлял ответ, "
            "поэтому не спрашивай, что он уже пробовал. Не объясняй тему, пока он "
            "не ответил."
        )
    else:
        opening = (
            "Начни разговор: поздоровайся одной строкой и спроси, как ученик "
            "рассуждал и что уже попробовал. Не объясняй тему и не разбирай "
            "задание, пока он не ответил."
        )
    return f"{build_context_block(view, student_answer)}\n\n{opening}"
