"""Вопрос ученику «в каком ты классе»: кому показывать и как его закрыть (tsk-741).

Класс (`users.school_grade`, tsk-427) существует давно, но заполнен у 5 человек
из 82: поле лежало в профиле, куда ученик не заходит. А от класса зависит срок
подготовки к экзамену — 11 класс сдаёт в июне 2027, 10 класс годом позже, — и
значит весь недельный объём домашней работы. Решение оператора (29.08): спросить
в кабинете при входе, один раз, никого не блокируя.

Что важно помнить читающему:

- **Показ и молчание — это одно решение, посчитанное на сервере.** Флаг едет в
  каждом ответе `/me` тем же способом, что напоминание об опросе (tsk-674) и об
  оплате (tsk-744): вопрос должен быть виден на ЛЮБОМ экране кабинета, а не
  только там, куда человек однажды зайдёт сам.
- **Вопрос закрывают два разных события.** Ответ — `school_grade` заполнен
  (или человек сказал «я не школьник», и тогда `category` уже не школьная).
  Отказ — `school_grade_declined_at`. Оба гасят флаг, но различимы: отказавшихся
  оператор добирает лично, и по колонке видно, кого именно.
- **Аудитория — та же, что у опроса по расписанию** (`schedule_preference_service`),
  и по той же причине: учащиеся, кроме выпускников (`alumni`) и демо (`demo`).
  Тестовым учёткам вопрос показывается — иначе кабинет не на чем проверять.
- **Не-школьника не спрашиваем.** Если категория уже стоит и она не
  `school_student`, вопрос бессмысленный: человеку 30 лет, и «в каком ты классе»
  он прочтёт как поломку. Пустая категория — спрашиваем: у 77 из 82 она пуста, и
  это как раз те, ради кого всё затевалось.
"""
from __future__ import annotations

import logging

from sqlalchemy import text
from sqlalchemy.ext.asyncio import AsyncSession

from app.services.schedule_preference_service import AUDIENCE_FROM

logger = logging.getLogger(__name__)

#: Категория, при которой вопрос про класс имеет смысл. Пустая категория тоже
#: подходит — она у большинства и означает «мы просто ещё не спрашивали».
_SCHOOL_CATEGORY = "school_student"

#: Условие «вопрос про класс ещё открыт» — одно на показ и на подсчёт охвата.
#: Держится строкой, а не двумя копиями в разных запросах: разъехавшись, они
#: дадут «в кабинете спрашивают, а в сводке человек уже отвечен».
OPEN_QUESTION_SQL = f"""
    u.school_grade IS NULL
    AND u.school_grade_declined_at IS NULL
    AND (u.category IS NULL OR u.category = '{_SCHOOL_CATEGORY}')
"""


async def is_pending(db: AsyncSession, user_id: int) -> bool:
    """Показывать ли этому человеку вопрос про класс.

    Один запрос: флаг читается на каждой загрузке профиля.

    Args:
        db: async session.
        user_id: ID пользователя.

    Returns:
        True — человек в аудитории и вопрос ещё открыт.
    """
    row = (
        await db.execute(
            text(
                f"""
                SELECT 1
                {AUDIENCE_FROM} AND u.id = :uid
                  AND {OPEN_QUESTION_SQL}
                LIMIT 1
                """
            ),
            {"uid": user_id},
        )
    ).first()
    return row is not None


async def decline(db: AsyncSession, user_id: int) -> None:
    """Записать отказ отвечать: вопрос закрыт, больше не показываем.

    Идемпотентна: повторный вызов не сдвигает уже стоящую дату — первая
    попытка и есть та, о которой стоит помнить оператору. Ответивших не
    трогает вовсе: у них вопрос закрыт ответом, и пометка отказа сделала бы
    их неотличимыми от молчунов в сводке.

    Args:
        db: async session.
        user_id: ID пользователя.
    """
    await db.execute(
        text(
            """
            UPDATE users
               SET school_grade_declined_at = now()
             WHERE id = :uid
               AND school_grade_declined_at IS NULL
               AND school_grade IS NULL
            """
        ),
        {"uid": user_id},
    )
    logger.info("tsk-741: вопрос про класс закрыт отказом, user_id=%s", user_id)
